window.규칙 = (() => {
  const 상수 = {
    "사양오차": .9,
    "노후배터리": .67,
    "화면값보정": .9,
    "출력여유배수": 1.2,
    "인버터효율": .85,
    "도로우회계수": 1.4,
    "이동시속km": 25,
    "이송판단h": 1
  };
  const 무배터리산소 = new Set([ "D10", "D11" ]);
  const 반올림 = h => Math.round(h * 100) / 100;
  function 기기안전시간(기기, 상태) {
    const 과정 = [], 경고 = [];
    let 사양h;
    if (!기기.표준h) {
      사양h = 0;
    } else if (기기.최악h !== null) {
      사양h = 기기.최악h * 상수.사양오차 * 상수.노후배터리;
      과정.push({
        "식": `사양 최악조건 ${기기.최악h}h × ${상수.사양오차} × ${상수.노후배터리}`,
        "값": 사양h,
        "등급": "A"
      });
    } else {
      사양h = (기기.표준h || 0) * 상수.사양오차 * 상수.노후배터리;
      if (기기.표준h) {
        과정.push({
          "식": `사양 표준조건 ${기기.표준h}h × ${상수.사양오차} × ${상수.노후배터리}`,
          "값": 사양h,
          "등급": "A"
        });
        경고.push(`${기기.모델}: 최악 조건 미공개, 표준 조건 기준`);
      }
    }
    const 배터리있음 = Boolean(기기.표준h);
    let h = 사양h;
    if (배터리있음 && 상태.근거 === "B" && 상태.기기화면_남은시간h !== null) {
      h = 상태.기기화면_남은시간h * 상수.화면값보정;
      과정.push({
        "식": `기기 화면 남은 시간 ${상태.기기화면_남은시간h}h × ${상수.화면값보정} (사양값 대신)`,
        "값": h,
        "등급": "B"
      });
    } else if (배터리있음 && 상태.근거 === "C" && 상태.충전량pct !== null) {
      const pct = Math.min(상태.충전량pct, 100);
      h = 사양h * pct / 100;
      과정.push({
        "식": `보호자 입력 충전량 ${pct}% 적용 (줄이기만 함)`,
        "값": h,
        "등급": "C"
      });
      경고.push("충전량은 보호자 입력값(C) — 수동 확인 권장");
    }
    if (!배터리있음) {
      과정.push({
        "식": 기기.종류.includes("산소발생기") ? "내장 배터리 없음" : "배터리 시간 표기 없음",
        "값": 0,
        "등급": "A"
      });
      if (기기.W > 0 && !기기.종류.includes("산소발생기")) 경고.push(`${기기.모델}: 배터리 시간 표기 없음 → 0시간으로 계산`);
    }
    return {
      h: h,
      "과정": 과정,
      "경고": 경고
    };
  }
  function 가구안전시간(가구, 기기표) {
    const 기기별 = [], 경고 = [];
    가구.기기.forEach(((기기ID, 순번) => {
      const 기기 = 기기표[기기ID];
      const 상태 = 순번 === 0 ? 가구.상태 : {
        "근거": "A"
      };
      const r = 기기안전시간(기기, 상태);
      경고.push(...r.경고);
      const 외장 = 가구.외장배터리;
      if (외장.개수 && 기기.외장h) {
        if (외장.사양확인) {
          const 더함 = 외장.개수 * 기기.외장h * 상수.사양오차 * 상수.노후배터리;
          r.h += 더함;
          r.과정.push({
            "식": `+ 정품 외장배터리 ${외장.개수}개 × ${기기.외장h}h × ${상수.사양오차} × ${상수.노후배터리}`,
            "값": r.h,
            "등급": "A"
          });
        } else {
          r.과정.push({
            "식": "외장배터리 사양 미확인 → 더하지 않음",
            "값": r.h,
            "등급": "C"
          });
          경고.push("외장배터리 사양 미확인 → 계산 제외, 수동 확인");
        }
      }
      if (무배터리산소.has(기기ID)) {
        const 산소 = 가구.예비산소통;
        if (산소.시간h && 산소.업체확인) {
          r.h += 산소.시간h;
          r.과정.push({
            "식": `+ 예비 산소통 ${산소.시간h}h (대여업체 확인)`,
            "값": r.h,
            "등급": "A"
          });
        } else if (산소.시간h) {
          r.과정.push({
            "식": `예비 산소통 ${산소.시간h}h — 보호자 입력이라 더하지 않음`,
            "값": r.h,
            "등급": "C"
          });
          경고.push("예비 산소통은 보호자 입력값 → 계산 제외, 수동 확인");
        }
      }
      기기별.push({
        "기기ID": 기기ID,
        "기기": 기기,
        h: r.h,
        "과정": r.과정
      });
    }));
    const h = Math.min(...기기별.map((d => d.h)));
    return {
      h: h,
      "기기별": 기기별,
      "경고": [ ...new Set(경고) ]
    };
  }
  function 거리km(a, b) {
    const r = 6371, rad = Math.PI / 180;
    const φ1 = a.위도 * rad, φ2 = b.위도 * rad;
    const dφ = φ2 - φ1, dλ = (b.경도 - a.경도) * rad;
    const x = Math.sin(dφ / 2) ** 2 + Math.cos(φ1) * Math.cos(φ2) * Math.sin(dλ / 2) ** 2;
    return 2 * r * Math.asin(Math.sqrt(x));
  }
  function 도착h(자원, 가구) {
    return 거리km(자원, 가구) * 상수.도로우회계수 / 상수.이동시속km + 자원.준비분 / 60;
  }
  function 호환(자원, 가구, 기기표) {
    if (!자원.가용) return {
      "사유": 자원.메모 || "사용 불가"
    };
    const 기기들 = 가구.기기.map((d => 기기표[d]));
    if (자원.산소h) {
      if (가구.기기.every((d => 무배터리산소.has(d)))) return {
        "방식": "예비 산소통",
        "공급h": 자원.산소h
      };
      return {
        "사유": "산소통 — 이 가구 기기에 해당 없음"
      };
    }
    const 합계W = 기기들.reduce(((s, d) => s + d.W), 0);
    const 필요W = 합계W * 상수.출력여유배수;
    const 남은Wh = 자원.용량Wh * 자원.잔량pct / 100 * 상수.인버터효율;
    if (자원.AC_W >= 필요W) return {
      "방식": "AC 220V",
      "공급h": 남은Wh / 합계W
    };
    const dc가능 = 가구.DC전용케이블 && 기기들.every((d => d.DC12)) && 자원.DC12_W >= 필요W;
    if (dc가능) return {
      "방식": "DC 12V(전용 케이블)",
      "공급h": 남은Wh / 합계W
    };
    let 사유 = `AC 출력 ${자원.AC_W}W < 필요 ${Math.round(필요W)}W`;
    if (!가구.DC전용케이블) 사유 += " · DC 전용 케이블 없음"; else if (!기기들.every((d => d.DC12))) 사유 += " · 기기가 DC 12V 직결 불가"; else 사유 += ` · DC 출력 ${자원.DC12_W}W 부족`;
    return {
      "사유": 사유
    };
  }
  function 판정(가구목록, 자원목록, 복구표, 기기표, 고정 = {}) {
    const 결과 = 가구목록.map((가구 => {
      const 안전 = 가구안전시간(가구, 기기표);
      const 복구 = 복구표[가구.정전원인];
      const 자원평가 = 자원목록.map((자원 => {
        const c = 호환(자원, 가구, 기기표);
        return {
          "자원": 자원,
          "도착h": 도착h(자원, 가구),
          ...c
        };
      })).sort(((a, b) => (a.방식 ? 0 : 1) - (b.방식 ? 0 : 1) || a.도착h - b.도착h));
      const 후보 = 자원평가.filter((c => c.방식));
      const 최선도착 = 후보.length ? 후보[0].도착h : Infinity;
      const 여유 = 안전.h - Math.min(복구.상한_h, 최선도착);
      return {
        "가구": 가구,
        "안전h": 안전.h,
        "기기별": 안전.기기별,
        "경고": 안전.경고,
        "복구": 복구,
        "자원평가": 자원평가,
        "후보": 후보,
        "최선도착": 최선도착,
        "여유": 여유
      };
    }));
    결과.sort(((a, b) => a.여유 - b.여유));
    const 사용된 = new Set;
    for (const r of 결과) {
      const 자원id = 고정[r.가구.id];
      if (!자원id) continue;
      const c = r.후보.find((x => x.자원.id === 자원id));
      if (c && !사용된.has(자원id)) {
        사용된.add(자원id);
        r.배정 = 배정정보(r, c);
        r.고정됨 = true;
      }
    }
    for (const r of 결과) {
      if (r.배정) continue;
      const 상한 = r.복구.상한_h;
      if (r.안전h >= 상한) {
        r.배정 = null;
        r.상태 = {
          "코드": "ok",
          "글": "자원 불필요",
          "설명": "복구 상한까지 버팀 — 대기 안내"
        };
        continue;
      }
      const 남은 = r.후보.filter((c => !사용된.has(c.자원.id)));
      if (!남은.length) {
        r.배정 = null;
        r.상태 = r.안전h < 상수.이송판단h ? {
          "코드": "crit",
          "글": "119 연계 검토",
          "설명": "호환·가용 자원 없음"
        } : {
          "코드": "short",
          "글": "자원 부족 대기",
          "설명": "자원 추가 확보·회수 필요"
        };
        continue;
      }
      const 제때 = 남은.filter((c => c.도착h <= r.안전h));
      const c = (제때.length ? 제때 : 남은)[0];
      사용된.add(c.자원.id);
      r.배정 = 배정정보(r, c);
    }
    return 결과;
  }
  function 배정정보(r, c) {
    const 상한 = r.복구.상한_h;
    const 필요h = 상한 - c.도착h;
    const 배정 = {
      "자원": c.자원,
      "방식": c.방식,
      "도착h": c.도착h,
      "공급h": c.공급h,
      "필요h": 필요h
    };
    if (c.도착h > r.안전h) {
      r.상태 = {
        "코드": "crit",
        "글": "119 연계 검토",
        "설명": "자원 도착 전 소진 위험 — 이송 검토 + 자원 출동"
      };
    } else if (c.공급h < 필요h) {
      r.상태 = {
        "코드": "assign",
        "글": "배정 추천",
        "설명": `공급 ${시간(c.공급h)} < 필요 ${시간(필요h)} — 교대 필요`
      };
      배정.교대 = true;
    } else {
      r.상태 = {
        "코드": "assign",
        "글": "배정 추천",
        "설명": "복구 상한까지 공급 가능"
      };
    }
    return 배정;
  }
  function 시간(h) {
    if (!isFinite(h)) return "—";
    const 부호 = h < 0 ? "−" : "";
    const 분 = Math.round(Math.abs(h) * 60);
    return `${부호}${Math.floor(분 / 60)}:${String(분 % 60).padStart(2, "0")}`;
  }
  return {
    "상수": 상수,
    "판정": 판정,
    "가구안전시간": 가구안전시간,
    "호환": 호환,
    "도착h": 도착h,
    "시간": 시간,
    "반올림": 반올림
  };
})();
